// Builds the planning pilot's demo data (#195) from the repository's stored records for the three Tennessee pilot
// schools. Records are copied unchanged, verification status included, so the engine decides what is a fact; only
// business programs and the domains the roadmap reads are kept, to keep the demo bundle small.
//
//   npx vite-node scripts/buildPilotFixture.ts      (rewrites src/features/planning/pilotFixture.json)
// scripts/pilotFixture.test.ts fails when the stored records change and the fixture wasn't rebuilt.
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(__dirname, '../../data')
export const PILOT_YEAR = '2026-27'
export const PILOT_SCHOOLS = [
  { key: 'utc', unitid: '221740' },
  { key: 'utk', unitid: '221759' },
  { key: 'mtsu', unitid: '220978' },
] as const
const DOMAINS = ['academic_programs', 'degree_requirements', 'credit_policies', 'costs'] as const
const isBusiness = (k: string) => /(b-s-b-a|bsba|bba)$/.test(k) || k.startsWith('economics-')

type Rec = Record<string, unknown>
function records(school: string, domain: string): Rec[] {
  const f = join(ROOT, 'institutions', school, domain, `${PILOT_YEAR}.json`)
  if (!existsSync(f)) return []
  const d = JSON.parse(readFileSync(f, 'utf8'))
  return ((d.records ?? []) as Rec[]).map((r) => ({ academic_year: d.academic_year ?? PILOT_YEAR, ...r }))
}
function identity(school: string, unitid: string): Rec {
  const own = join(ROOT, 'institutions', school, 'institution.json')
  if (existsSync(own)) {
    const i = JSON.parse(readFileSync(own, 'utf8'))
    return { institution_key: school, display_name: i.display_name, state_code: i.state_code, city: i.city, verification_status: i.verification_status, source_url: i.source_url, level: 'four_year' }
  }
  const dir = join(ROOT, 'national/ipeds')
  const year = readdirSync(dir).sort().at(-1)!
  const lines = readFileSync(join(dir, year, 'TN/institutions.csv'), 'utf8').trim().split('\n')
  const head = lines[0]!.split(',')
  const row = Object.fromEntries(head.map((h, i) => [h, lines.find((l) => l.split(',')[2] === unitid)!.split(',')[i]]))
  return { institution_key: school, display_name: row.display_name, state_code: row.state_code, city: row.city, verification_status: row.verification_status, source_url: row.source_url, level: row.level }
}

export function buildPilotFixture() {
  return {
    note: 'Generated by web/scripts/buildPilotFixture.ts from data/institutions (records unchanged). Demo use only, behind VITE_PLANNING_PILOT.',
    academic_year: PILOT_YEAR,
    schools: PILOT_SCHOOLS.map(({ key, unitid }) => {
      const programs = records(key, 'academic_programs').filter((p) => isBusiness(String(p.program_key)))
      const keys = new Set(programs.map((p) => p.program_key))
      return {
        institution_key: key,
        institution: identity(key, unitid),
        domains: {
          academic_programs: programs,
          degree_requirements: records(key, 'degree_requirements').filter((r) => keys.has(r.program_key)),
          credit_policies: records(key, 'credit_policies'),
          costs: records(key, 'costs'),
        },
      }
    }),
  }
}
export { DOMAINS }
